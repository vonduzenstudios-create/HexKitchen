let cache: Map<string, string[]> | null = null;

/** Word (uppercase) -> phonemes with stress digits, e.g. ["G","AO1","R","G","AH0","N"]. */
export function getDict(): Map<string, string[]> {
  if (cache) return cache;
  const m = new Map<string, string[]>();
  for (const line of RAW_DICT.split('\n')) {
    const t = line.trim();
    if (!t) continue;
    const parts = t.split(/\s+/);
    const w = parts.shift()!;
    m.set(w, parts);
  }
  cache = m;
  return m;
}

